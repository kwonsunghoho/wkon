// 무엇을 지키는 검사인가 ──────────────────────────────────────────────────────
//   ⚠️ **자소서 문항은 채용마다 바뀐다**(2026-07-25 오너). 바뀐 문항에 지난 채용의
//      주의사항을 들이대면 학생을 틀린 방향으로 끌고 간다.
//      그래서 중계 함수는 학생이 입력한 문항을 airline_profiles 의 문항과 견주어,
//      **같을 때만** 문항별 조언을 싣는다.
//
//   이 스크립트는 그 판정이 흔들리지 않는지 본다. 임계값(Q_MATCH_MIN)이나 유사도 식을
//   고치면 **반드시 여기를 돌려 기준선과 비교할 것**(뉴스 수집기 --dry-run, ai-killer-dryrun 과 같은 역할).
//
//   ⚠️ 판정은 **일부러 보수적이다.** 애매하면 '불일치'로 기운다 —
//      틀린 조언을 하는 것보다 조언을 덜 하는 편이 낫기 때문이다.
//      그래서 학생이 문항을 아주 짧게 줄여 쓰면(예: "최근 관심사와 이유") 놓친다.
//      이건 버그가 아니라 설계다. 대신 화면이 "문항을 그대로 붙여넣으면 더 정확해요"로 안내한다.
// =============================================================================

// ⚠️ supabase/functions/ai-killer/index.ts 의 qSimilarity 와 **같은 식**이어야 한다.
//    한쪽만 고치면 이 검사가 실제 동작을 못 지킨다.
function qSimilarity(studentQ, profileQ) {
  const norm = (s) => s.replace(/[\s\p{P}\p{S}]/gu, '').toLowerCase();
  const a = norm(studentQ), b = norm(profileQ);
  if (a.length < 6 || b.length < 6) return 0;   // 너무 짧으면 우연히 겹친다
  const bi = (s) => {
    const g = new Set();
    for (let i = 0; i < s.length - 1; i++) g.add(s.slice(i, i + 2));
    return g;
  };
  const ga = bi(a), gb = bi(b);
  let hit = 0;
  for (const g of ga) if (gb.has(g)) hit++;
  return hit / ga.size;   // 학생은 문항을 줄여 쓴다 → 자카드가 아니라 '입력이 원문에 담긴 비율'
}
const Q_MATCH_MIN = 0.62;

const 제주1 = '제주항공의 핵심가치(안전/효율/전문성/열린사고/협력) 중 본인이 가장 중요하게 여기는 가치를 선택하고, 그 이유와 이를 바탕으로 제주항공에 지원하게 된 동기를 서술해 주십시오.';
const 티웨이2 = '최근 3개월 내 개인적으로 가장 관심을 갖고 있는 것과 그 이유에 대하여 작성하여 주십시오. (항공업 관련 내용 제외)';
const 에프3 = '에어프레미아 Work Code 15가지 중 가장 공감하는 것과 가장 공감하기 어려운 것을 하나씩 선택해 주세요.';

const CASES = [
  // [설명, 학생 입력, 프로필 문항, 기대]
  ['원문 그대로 붙여넣기',            제주1, 제주1, true],
  ['적당히 줄여 씀',                  '핵심가치 중 가장 중요하게 여기는 가치와 지원동기', 제주1, true],
  ['많이 줄여 씀',                    '핵심가치와 지원동기', 제주1, true],
  ['티웨이 원문',                     티웨이2, 티웨이2, true],
  ['에프 원문',                       에프3, 에프3, true],

  // ⚠️ 아래는 전부 **불일치가 정답**이다. 하나라도 true 로 뒤집히면 위험하다.
  ['요구가 바뀐 차기 채용 문항',      '제주항공의 핵심가치 중 하나를 선택해 본인의 경험과 연결하여 서술해 주십시오.', 제주1, false],
  ['완전히 다른 새 문항',             '입사 후 이루고 싶은 목표와 그 이유를 서술해 주십시오.', 제주1, false],
  ['다른 항공사 문항이 섞임',         '최근 트렌드 중 티웨이항공과 연관이 있다고 생각하는 것', 제주1, false],
  ['티웨이 자리에 제주 문항',         제주1, 티웨이2, false],
  ['한 단어만 입력',                  '강점', 제주1, false],
  ['너무 짧은 축약(놓치는 게 정상)',  '최근 관심사와 이유', 티웨이2, false],
];

let bad = 0;
console.log('문항 매칭 — 임계값 ' + Q_MATCH_MIN + '\n');
for (const [name, s, p, want] of CASES) {
  const score = qSimilarity(s, p);
  const got = score >= Q_MATCH_MIN;
  const ok = got === want;
  if (!ok) bad++;
  console.log(`  ${ok ? 'OK  ' : 'FAIL'}  ${score.toFixed(2)}  ${got ? '일치  ' : '불일치'}  ${name}`);
}
console.log('\n' + '─'.repeat(64));
if (bad) {
  console.log(`⚠️ ${bad}건이 기대와 다르다. 임계값을 되돌리거나 유사도 식을 다시 볼 것.`);
  console.log('   특히 **불일치 케이스가 일치로 뒤집히는 것**이 위험하다 —');
  console.log('   바뀐 문항에 지난 채용 주의사항을 들이대게 된다.');
  process.exit(1);
}
console.log('전부 기대대로. (기준선 2026-07-25: 일치 5건 · 불일치 6건)');
