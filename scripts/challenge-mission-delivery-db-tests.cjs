'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { randomUUID, generateKeyPairSync, randomBytes } = require('node:crypto');
const { PGlite } = require('@electric-sql/pglite');
// 테스트 DB 안의 net.http_post는 요청을 기록하고 실제 알림을 보내지 않는다.
const migrationPath = path.join(
  __dirname,
  '../supabase/migrations/20261126105000_challenge_room_midnight.sql',
);
function workerSql() {
  const full = fs.readFileSync(migrationPath, 'utf8');
  const start = full.indexOf('create table challenge_room_data.push_deliveries (');
  assert.notEqual(start, -1, '운영 마이그레이션에 전송 대기열 정의가 있어야 합니다.');
  return full.slice(start);
}
const fixtureKey = 'harness-anon-jwt-only';
const bootstrap = `
create role anon;
create role authenticated;
create role service_role bypassrls;
create schema cron;
create schema vault;
create schema net;
create schema challenge_room_data;
create table public.challenge_rounds(id uuid primary key, challenge text not null,round integer not null);
create table challenge_room_data.missions(id uuid primary key,round_id uuid not null references public.challenge_rounds(id),day_no smallint not null,release_date date not null,opens_at timestamptz not null,title text not null,body text not null);
create table challenge_room_data.devices(id uuid primary key,member_id uuid not null,endpoint text not null unique,p256dh text not null,auth_key text not null,created_at timestamptz not null);
create table challenge_room_data.subscriptions(device_id uuid references challenge_room_data.devices on delete cascade, round_id uuid references public.challenge_rounds on delete cascade, enabled_at timestamptz not null, primary key(device_id,round_id));
create table challenge_room_data.fixtures_eligible(member_id uuid, round_id uuid,primary key(member_id,round_id));
create function challenge_room_data.eligible(p_member uuid,p_round uuid) returns boolean language sql stable security definer set search_path='' as $$
select exists(select from challenge_room_data.fixtures_eligible where member_id=p_member and round_id=p_round)
$$;
create table vault.decrypted_secrets(name text primary key, decrypted_secret text not null);
create table net.requests(id bigint generated always as identity primary key, url text,headers jsonb,body jsonb);
create function net.http_post(url text,body jsonb default '{}'::jsonb,params jsonb default '{}'::jsonb,headers jsonb default '{"Content-Type":"application/json"}'::jsonb,timeout_milliseconds integer default 5000)
returns bigint language sql as $$insert into net.requests(url,headers,body) values($1,$4,$2) returning id$$;
create table cron.job(jobid bigint generated by default as identity,jobname text primary key,schedule text,command text);
create function cron.schedule(job_name text,schedule text,command text) returns bigint language sql as $$
insert into cron.job(jobname,schedule,command) values($1,$2,$3) on conflict (jobname) do update set schedule=excluded.schedule,command=excluded.command returning jobid
$$;
`;
const credentials = () => {
  const { privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
  const jwk = privateKey.export({ format: 'jwk' });
  const point = Buffer.concat([
    Buffer.from([4]),
    Buffer.from(jwk.x, 'base64url'),
    Buffer.from(jwk.y, 'base64url'),
  ]);
  return { publicKey: point.toString('base64url'), privateKey: jwk.d };
};
async function main() {
  const tests = [];
  const db = new PGlite();
  const q = async (s, args = []) => (await db.query(s, args)).rows;
  const first = async (s, args = []) => (await q(s, args))[0];
  const exec = (s) => db.exec(s);
  const check = (summary, fn) => fn().then(() => tests.push(summary));
  const role = async (name, fn) => {
    await exec('set role ' + name);
    try {
      return await fn();
    } finally {
      await exec('reset role');
    }
  };
  const worker = (a, d, as = 'service_role') =>
    role(
      as,
      async () =>
        (await first('select public.challenge_push_worker($1,$2::jsonb) as value', [
          a,
          JSON.stringify(d),
        ])).value,
    );
  const tick = () => q('select challenge_room_data.push_tick()');
  const reqs = () => q('select id,url,headers,body from net.requests order by id');
  const pushToken = async () => {
    const before = (await reqs()).length;
    await tick();
    const list = await reqs();
    assert.equal(list.length, before + 1, 'tick must dispatch one new eligible batch');
    const { url, headers, body } = list.at(-1);
    assert.equal(
      url,
      'https://apzwauiumhmsvrgffjis.supabase.co/functions/v1/challenge-mission-push',
    );
    assert.equal(headers.apikey, fixtureKey);
    assert.equal(headers.Authorization || headers.authorization, 'Bearer ' + fixtureKey);
    assert.equal(body.action, 'dispatch');
    assert(typeof body.token === 'string' && body.token.length >= 32);
    return body.token;
  };
  const enroll = async (round, member) =>
    q('insert into challenge_room_data.fixtures_eligible values($1,$2) on conflict do nothing', [
      member,
      round,
    ]);
  const mission = async (round, offsetSeconds, day = 1) => {
    const id = randomUUID();
    await q(
      "insert into challenge_room_data.missions values($1,$2,$3, ((now()+$4::int*'1 second'::interval) at time zone 'Asia/Seoul')::date,now()+$4::int*'1 second'::interval,'synthetic title','synthetic body')",
      [id, round, day, offsetSeconds],
    );
    return id;
  };
  const device = async (round, options = {}) => {
    const member = options.member || randomUUID(),
      device = randomUUID(),
      created = options.offset ?? -600;
    const publicKey = credentials().publicKey, auth = randomBytes(16).toString('base64url');
    const endpoint = 'https://fcm.googleapis.com/fcm/send/harness-' + device;
    await q(
      "insert into challenge_room_data.devices values($1,$2,$3,$4,$5,now()-interval '1 day')",
      [device, member, endpoint, publicKey, auth],
    );
    if (!options.noEnrollment) await enroll(round, member);
    await q(
      "insert into challenge_room_data.subscriptions values($1,$2,now()+$3::int*'1 second'::interval)",
      [device, round, created],
    );
    return { member, device, endpoint, auth, publicKey };
  };
  const removeSub = (device, round) =>
    q('delete from challenge_room_data.subscriptions where device_id=$1 and round_id=$2', [
      device,
      round,
    ]);
  const batch = async (token) => (await worker('claim', { token })).deliveries;
  const expectForbidden = async (fn) => {
    await assert.rejects(fn, (e) => e.code === '42501');
  };
  const round = randomUUID(), otherRound = randomUUID();
  try {
    await exec(bootstrap);
    await q('insert into vault.decrypted_secrets values($1,$2)', ['monc_anon_jwt', fixtureKey]);
    await exec(workerSql());
    await check('installed gated scheduler', async () => {
      const jobs = await q('select schedule,command from cron.job');
      assert.equal(jobs.length, 1);
      assert.equal(jobs[0].schedule, '* * * * *');
      assert(jobs[0].command.includes('push_tick'));
      assert(!jobs[0].command.includes(fixtureKey));
      await tick();
      assert.equal((await reqs()).length, 0);
    });
    await check('worker access limited to service role', async () => {
      const perm = (await q(
        "select has_function_privilege('anon','public.challenge_push_worker(text,jsonb)','execute') as anon, has_function_privilege('authenticated','public.challenge_push_worker(text,jsonb)','execute') as member, has_function_privilege('service_role','public.challenge_push_worker(text,jsonb)','execute') as worker",
      ))[0];
      assert.deepEqual(perm, { anon: false, member: false, worker: true });
      for (const actor of ['anon', 'authenticated']) {
        for (const verb of ['claim', 'finish', 'vapid']) {
          await assert.rejects(() => worker(verb, {}, actor), (e) => e.code === '42501');
        }
      }
    });
    await check('single persisted VAPID keypair', async () => {
      const pair = credentials(), second = credentials();
      assert.deepEqual(await worker('vapid', pair), pair);
      assert.deepEqual(await worker('vapid', second), pair);
    });
    await q("insert into public.challenge_rounds values($1,'voice',7),($2,'voice',8)", [
      round,
      otherRound,
    ]);
    const due = await mission(round, -60);
    await mission(round, 600, 2);
    await mission(round, -60 * 60 * 25, 3);
    await check('stale/late/other cohort prefilter', async () => {
      await device(otherRound);
      await device(round, { offset: -5 });
      await device(round, { noEnrollment: true });
      await tick();
      assert.equal((await reqs()).length, 0);
    });
    const good = await device(round);
    const nowOff = await device(round);
    const nowRefund = await device(round);
    let delivery;
    await check('claim excludes unsubscribed/refunded and protects one-use token', async () => {
      const token = await pushToken();
      await tick();
      assert.equal(
        (await reqs()).length,
        1,
        'repeated tick must not dispatch duplicate active tickets',
      );
      await removeSub(nowOff.device, round);
      await q(
        'delete from challenge_room_data.fixtures_eligible where member_id=$1 and round_id=$2',
        [nowRefund.member, round],
      );
      await expectForbidden(() => batch(randomUUID()));
      const entries = await batch(token);
      assert.equal(entries.length, 1);
      delivery = entries[0];
      assert.equal(delivery.mission_id, due);
      assert.equal(delivery.endpoint, good.endpoint);
      assert.deepEqual(delivery.keys, { p256dh: good.publicKey, auth: good.auth });
      assert.equal(delivery.day_no, 1);
      assert.equal(delivery.round, 7);
      assert.equal(delivery.challenge, 'voice');
      await expectForbidden(() => batch(token));
    });
    await check('lease ownership and sent deduplication', async () => {
      const fake = await worker('finish', { id: delivery.id, lease: randomUUID(), status: 'sent' });
      assert.equal(fake.ok, false);
      const done = await worker('finish', {
        id: delivery.id,
        lease: delivery.lease,
        status: 'sent',
      });
      assert.equal(done.ok, true);
      const again = await worker('finish', {
        id: delivery.id,
        lease: delivery.lease,
        status: 'sent',
      });
      assert.equal(again.ok, false);
      await tick();
      assert.equal((await reqs()).length, 1, 'completed recipient should not be redispatched');
    });
    await check('gone endpoint unsubscribe', async () => {
      const gone = await device(round);
      const [d] = await batch(await pushToken());
      assert.equal(d.endpoint, gone.endpoint);
      assert.equal((await worker('finish', { id: d.id, lease: d.lease, status: 'gone' })).ok, true);
      const remaining = await q(
        'select d.id from challenge_room_data.devices d join challenge_room_data.subscriptions s on s.device_id=d.id where d.id=$1',
        [gone.device],
      );
      assert.equal(remaining.length, 0);
      await tick();
      assert.equal((await reqs()).length, 2);
    });
    await check(
      'single claim capped at 50; multiple batches drain without duplicate delivery id',
      async () => {
        const ids = new Set();
        // 서로 다른 55개 기기를 한 번에 등록해 배치 경계를 검증한다.
        await q(
          "with m as(select gen_random_uuid() id from generate_series(1,55)),eligible as(insert into challenge_room_data.fixtures_eligible select id,$1 from m), devices as(insert into challenge_room_data.devices(id,member_id,endpoint,p256dh,auth_key,created_at) select id,id,'https://fcm.googleapis.com/fcm/send/test-'||id,'test-key','test-auth',now()-interval '1 day' from m returning id) insert into challenge_room_data.subscriptions(device_id,round_id,enabled_at) select id,$1,now()-interval '20 minutes' from devices",
          [round],
        );
        let entries = await batch(await pushToken());
        assert.equal(entries.length, 50);
        for (const row of entries) {
          assert(!ids.has(row.id));
          ids.add(row.id);
          assert.equal(
            (await worker('finish', { id: row.id, lease: row.lease, status: 'sent' })).ok,
            true,
          );
        }
        entries = await batch(await pushToken());
        assert.equal(entries.length, 5);
        for (const row of entries) {
          assert(!ids.has(row.id));
          ids.add(row.id);
          assert.equal(
            (await worker('finish', { id: row.id, lease: row.lease, status: 'failed' })).ok,
            true,
          );
        }
        assert.equal(ids.size, 55);
        const before = (await reqs()).length;
        await tick();
        assert.equal((await reqs()).length, before);
      },
    );
    await check(
      'retry uses backoff; old lease cannot finalize after reclaim; max six push attempts',
      async () => {
        const d = await device(round);
        let [job] = await batch(await pushToken());
        assert.equal(job.endpoint, d.endpoint);
        await q(
          "update challenge_room_data.push_deliveries set next_at=now()-interval '1 second' where id=$1",
          [job.id],
        );
        const [reclaimed] = await batch(await pushToken());
        assert.equal(reclaimed.id, job.id);
        assert.notEqual(job.lease, reclaimed.lease);
        assert.equal(
          (await worker('finish', { id: job.id, lease: job.lease, status: 'sent' })).ok,
          false,
        );
        job = reclaimed;
        for (let n = 2; n <= 6; n++) {
          assert.equal(
            (await worker('finish', { id: job.id, lease: job.lease, status: 'retry' })).ok,
            true,
          );
          const row = await first(
            'select state,attempts,next_at>now() as delayed from challenge_room_data.push_deliveries where id=$1',
            [job.id],
          );
          assert.equal(row.state, n < 6 ? 'pending' : 'failed');
          assert.equal(row.attempts, n);
          assert.equal(row.delayed, true);
          const before = (await reqs()).length;
          await tick();
          assert.equal((await reqs()).length, before);
          if (n < 6) {
            await q(
              "update challenge_room_data.push_deliveries set next_at=now()-interval '1 second' where id=$1",
              [job.id],
            );
            [job] = await batch(await pushToken());
          }
        }
      },
    );
    await check('expired tickets rejected, tick recovers after gateway loss', async () => {
      const d = await device(round);
      const oldTicket = await pushToken();
      await q("update challenge_room_data.push_tickets set expires_at=now()-interval '1 second'");
      await assert.rejects(() => batch(oldTicket), (e) => e.code === '42501');
      const token = await pushToken();
      assert.notEqual(token, oldTicket);
      const [j] = await batch(token);
      assert.equal(j.endpoint, d.endpoint);
      assert.equal((await worker('finish', { id: j.id, lease: j.lease, status: 'sent' })).ok, true);
    });
    await check('late gone delivery cannot erase refreshed browser subscription', async () => {
      const d = await device(round);
      const [j] = await batch(await pushToken());
      await q("update challenge_room_data.devices set auth_key='different-key' where id=$1", [
        d.device,
      ]);
      assert.equal((await worker('finish', { id: j.id, lease: j.lease, status: 'gone' })).ok, true);
      assert.equal(
        (await q('select id from challenge_room_data.devices where id=$1', [d.device])).length,
        1,
      );
    });
    await check('missing gateway key pauses safely and recovers when restored', async () => {
      const d = await device(round);
      await q("delete from vault.decrypted_secrets where name='monc_anon_jwt'");
      const before = (await reqs()).length;
      await tick();
      assert.equal((await reqs()).length, before);
      assert.equal((await q('select * from challenge_room_data.push_tickets')).length, 0);
      await q('insert into vault.decrypted_secrets values($1,$2)', ['monc_anon_jwt', fixtureKey]);
      const [j] = await batch(await pushToken());
      assert.equal(j.endpoint, d.endpoint);
      assert.equal((await worker('finish', { id: j.id, lease: j.lease, status: 'sent' })).ok, true);
    });
    console.log('PASS ' + tests.length + ' cases: ' + tests.join(', '));
  } finally {
    await db.close();
  }
}
main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
