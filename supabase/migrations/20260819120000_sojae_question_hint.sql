-- 소재 문제 예시 한 줄 (2026-08-19)
-- 사용자 피드백: "'추상적인 가치관을 설득력있게 풀기' 같은 질문이 어렵다 — 구체적인 예시가
-- 있으면 좋겠다". 문제마다 선택 입력하는 예시 한 줄을 추가한다.
-- 노출: 소재 발굴 고르기 카드('예시: …') + 첫 인사말('예를 들면 … 같은 것도 좋아요').
-- 비어 있으면 화면에 아무것도 안 보인다. 값은 admin '소재 문제' 탭에서 입력.
-- ⚠️ 예시 문구에 합격자 실제 문장·교재 원문을 넣지 않는다(공개 questions 테이블이다).

alter table public.questions add column if not exists hint text;

comment on column public.questions.hint is
  '예시 한 줄(선택) — 학생에게 "예를 들면 …" 으로 보여줄 구체 예시. 합격자 문장 금지';
