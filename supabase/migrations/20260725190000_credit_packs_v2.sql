-- 왜 바꾸나 ───────────────────────────────────────────────────────────────────
--   구 상품은 '10회 9,900원' 하나였다. 그런데 도구마다 단가가 달라졌으므로
--   (소재 2 / KILL AI 3 / 첨삭 10) **'회'가 아니라 '크레딧'을 판다.**
--
--   ⚠️ count 의 뜻이 바뀐다 — 구: 검사 횟수 / 신: **크레딧 개수**.
--      verify-payment 는 count 를 그대로 credit_ledger.delta 에 넣으므로 함수는 안 고쳐도 된다.
--
-- 가격 산정(2026-07-25 오너 확정) ────────────────────────────────────────────
--   만원 = 30크레딧. 크레딧당 판매가 333원(PG 수수료 3.3% 빼면 실수령 322원),
--   크레딧당 원가 약 80원 → 마진 75%.
--
--   ⚠️ 숫자의 근거는 마진이 아니라 **학생이 실제로 쓰는 단위**다.
--      자소서 한 문항을 끝까지 다듬으면 소재 2 + 킬러 2회 6 + 첨삭 10 = **18크레딧**.
--      만원 30크레딧이면 '한 문항 완성 + 검사 4회 여유'라 "조금 모자란데 하나는 제대로 되네"
--      지점에 앉는다 — 재구매가 자연스럽게 온다. 40~50 으로 올리면 재구매가 너무 늦다.
--
--   ⚠️ 집중 팩을 **챌린지 참가비와 같은 3만 원**에 둔 건 의도다. 이미 그 값을 내 본
--      사람들이라 결제 저항이 낮다.
-- =============================================================================

update public.site_config
   set value = '[
     {"id":"c14",  "tool":"ai_killer", "count":14,  "price":5000,  "label":"체험 14크레딧"},
     {"id":"c30",  "tool":"ai_killer", "count":30,  "price":10000, "label":"기본 30크레딧"},
     {"id":"c100", "tool":"ai_killer", "count":100, "price":30000, "label":"집중 100크레딧"}
   ]'::jsonb
 where key = 'credit_packs'
   -- 구 상품(ai10)이 그대로일 때만 갈아끼운다. 오너가 admin 에서 손봤으면 건드리지 않는다.
   and value @> '[{"id":"ai10"}]'::jsonb;

-- 설정 자체가 없으면(구 마이그레이션 미실행) 새로 넣는다
insert into public.site_config (key, value) values
  ('credit_packs', '[
     {"id":"c14",  "tool":"ai_killer", "count":14,  "price":5000,  "label":"체험 14크레딧"},
     {"id":"c30",  "tool":"ai_killer", "count":30,  "price":10000, "label":"기본 30크레딧"},
     {"id":"c100", "tool":"ai_killer", "count":100, "price":30000, "label":"집중 100크레딧"}
   ]')
on conflict (key) do nothing;

