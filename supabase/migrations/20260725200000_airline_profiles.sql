--      (문항 구성 · 문체 관습 · 회사 고유 소재)뿐이다. 문장을 그대로 옮기지 말 것.
--
--   ⚠️ **AI 에게 "이렇게 쓰라"고 합격자 문장을 주지 않는다**(확정본 결정 10).
--      그러면 모두가 비슷한 글이 되어, 우리가 잡으려는 AI스러움을 우리가 만든다.
--      여기 담는 건 '무엇을 쓸까'가 아니라 **'무엇을 보고 판단하나'**다 —
--      그 항공사가 실제로 묻는 것, 합격자들이 공통으로 지킨 형식, 회사 고유 소재.
--
--   ⚠️ RLS: **일반 회원은 읽을 수 없다**(사전 ai_killer_terms 와 같은 이유 — 경쟁사 복제 방지).
--      중계 함수(service role)와 관리자만 읽는다.
--
-- ⚠️ 미적용이어도 검사·첨삭은 정상 — 항공사 맥락만 빠진다(graceful degrade).
-- =============================================================================

create table if not exists public.airline_profiles (
  code        text primary key,             -- lecture-common.js 의 LEC.AIRLINES 와 같은 코드
  name        text not null,
  -- 그 항공사가 실제로 낸 자소서 문항. [{n, q, chars, note}]
  questions   jsonb not null default '[]'::jsonb,
  -- 문체 관습 — 합격자들이 공통으로 지킨 형식. {subhead, structure, tone, length}
  style       jsonb not null default '{}'::jsonb,
  -- 회사 고유 소재 — 합격자들이 인용한 제도·가치·최신 성과. 학생이 '조사했는지'가 여기서 갈린다.
  keywords    jsonb not null default '{}'::jsonb,
  -- 이 항공사만의 주의점(자유 문장). 프롬프트에 그대로 실린다.
  notes       text,
  sample_n    int not null default 0,       -- 근거가 된 합격 자소서 건수(신뢰도 표시)
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

comment on table public.airline_profiles is
  '항공사별 자소서 패턴. ⚠️ 비공개 — 일반 회원은 읽을 수 없다. 합격 자소서 원문은 절대 넣지 않는다(개인정보).';
comment on column public.airline_profiles.keywords is
  '회사 고유 소재(가치·제도·최신 성과). 학생이 회사를 조사했는지가 여기서 갈린다.';

drop trigger if exists trg_airline_profiles_updated on public.airline_profiles;
create trigger trg_airline_profiles_updated before update on public.airline_profiles
  for each row execute function public.set_updated_at();

alter table public.airline_profiles enable row level security;
drop policy if exists airline_profiles_admin on public.airline_profiles;
create policy airline_profiles_admin on public.airline_profiles
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

