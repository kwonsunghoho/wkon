-- =============================================================================
-- 1. ⚠️ 결제 멱등성 — 같은 결제로 두 번 충전되지 않게
-- =============================================================================
-- 브라우저가 verify-payment 를 두 번 부르는 길이 여럿이다:
--   PC 팝업 경로와 모바일 리다이렉트 복귀가 겹치는 경우 / 사용자가 새로고침 / 네트워크 재시도.
-- 중계 함수가 사전 조회로 막긴 하지만 조회와 insert 사이엔 늘 틈이 있다 —
-- **DB 가 마지막으로 막는다.**
--
-- (tool, ref) 로 잡는다. member_id 를 빼는 게 핵심: 결제 id 는 전역 고유하므로,
-- 같은 결제를 **다른 계정에** 충전하려는 시도까지 함께 막힌다.
create unique index if not exists credit_ledger_purchase_uq
  on public.credit_ledger (tool, ref) where reason = 'purchase';

-- =============================================================================
-- 2. 충전 상품 — site_config.credit_packs
-- =============================================================================
-- ⚠️ 금액은 **서버가 여기서 읽어 검증**한다(브라우저가 보낸 금액 불신).
--    admin '크레딧' 탭에서 바꾸면 즉시 반영된다 — Edge Function 재배포가 필요 없다
--    (함수가 요청마다 DB 를 읽으므로). 특강 가격과 같은 방식.
insert into public.site_config (key, value) values
  ('credit_packs', '[{"id":"ai10","tool":"ai_killer","count":10,"price":9900,"label":"10회"}]')
on conflict (key) do nothing;

